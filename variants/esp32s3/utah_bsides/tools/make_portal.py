"""Before each build: gzip tools/portal/index.html (the badge web page, with tools/portal/raven.png
inlined) into
generated/BadgePortalPage.h, which the badge serves with Content-Encoding: gzip."""
import base64
import gzip
import hashlib
import os

try:  # running inside PlatformIO
    Import("env")  # noqa: F821
    HERE = os.path.join(env.subst("$PROJECT_DIR"), "variants", "esp32s3", "utah_bsides")  # noqa: F821
except NameError:
    HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(HERE, "tools", "portal", "index.html")
OUT = os.path.join(HERE, "generated", "BadgePortalPage.h")


def main():
    with open(SRC, "rb") as fh:
        html = fh.read()
    with open(os.path.join(os.path.dirname(SRC), "raven.png"), "rb") as fh:  # inlined: one request
        html = html.replace(b'src="raven.png"', b'src="data:image/png;base64,' + base64.b64encode(fh.read()) + b'"')
    fp = hashlib.sha1(html).hexdigest()
    try:
        with open(OUT) as fh:
            if fp in fh.readline():
                return
    except OSError:
        pass
    data = gzip.compress(html, 9, mtime=0)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    lines = ["// %s - generated by tools/make_portal.py from tools/portal/index.html" % fp, "#pragma once",
             "#include <stddef.h>", "#include <stdint.h>", "namespace badge", "{",
             "static const uint8_t PORTAL_PAGE_GZ[] = {"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines += ["};", "static const size_t PORTAL_PAGE_GZ_LEN = sizeof(PORTAL_PAGE_GZ);", "} // namespace badge", ""]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print("[badge portal] page: %d KB, %d KB gzipped" % (len(html) // 1024, len(data) // 1024))


main()
