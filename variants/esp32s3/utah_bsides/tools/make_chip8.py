"""Before each build: chip8/*.ch8 and chip8/games.json -> generated/BadgeChip8Roms.h."""
import hashlib
import json
import os

try:  # running inside PlatformIO
    Import("env")  # noqa: F821
    HERE = os.path.join(env.subst("$PROJECT_DIR"), "variants", "esp32s3", "utah_bsides")  # noqa: F821
except NameError:
    HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DIR = os.path.join(HERE, "chip8")
OUT = os.path.join(HERE, "generated", "BadgeChip8Roms.h")
FLAGS = {"shiftQuirks": "shift", "loadStoreQuirks": "loadStore", "clipQuirks": "clip", "jumpQuirks": "jump",
         "vBlankQuirks": "vBlank", "logicQuirks": "logic"}


def main():
    with open(os.path.join(DIR, "games.json")) as fh:
        games = json.load(fh)
    blobs = []
    h = hashlib.sha1(json.dumps(games).encode())
    for g in games:
        with open(os.path.join(DIR, g["file"]), "rb") as fh:
            data = fh.read()
        h.update(data)
        blobs.append(data)
    fp = h.hexdigest()
    try:
        with open(OUT) as fh:
            if fp in fh.readline():
                return
    except OSError:
        pass
    L = ["// %s - generated by tools/make_chip8.py from chip8/ (CC0 games, see chip8/README.md)" % fp,
         "#pragma once", '#include "BadgeChip8.h"', "#include <stddef.h>", "namespace badge", "{",
         "struct Chip8Game {", "    const char *title;", "    const uint8_t *rom;", "    size_t len;",
         "    uint16_t tickrate;", "    Chip8Quirks quirks;", "};"]
    for i, data in enumerate(blobs):
        L.append("static const uint8_t CHIP8_ROM_%d[] = {" % i)
        for j in range(0, len(data), 24):
            L.append("    " + ", ".join("0x%02x" % b for b in data[j:j + 24]) + ",")
        L.append("};")
    L.append("static Chip8Quirks chip8Quirks(bool shift, bool loadStore, bool clip, bool jump, bool vBlank, bool logic)")
    L.append("{\n    Chip8Quirks q;\n    q.shift = shift, q.loadStore = loadStore, q.clip = clip, q.jump = jump, q.vBlank = vBlank, q.logic = logic;\n    return q;\n}")
    L.append("static const Chip8Game CHIP8_GAMES[] = {")
    for i, g in enumerate(games):
        q = ", ".join("true" if f in g.get("quirks", []) else "false" for f in FLAGS)
        title = g["title"].replace('"', "'")
        L.append('    {"%s", CHIP8_ROM_%d, sizeof(CHIP8_ROM_%d), %d, chip8Quirks(%s)},' % (title, i, i, int(g["tickrate"]), q))
    L += ["};", "static const int CHIP8_GAME_COUNT = %d;" % len(games), "} // namespace badge", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(L))
    print("[badge chip8] %d games, %d bytes" % (len(games), sum(len(b) for b in blobs)))


main()
